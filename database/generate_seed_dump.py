sql("--")
sql("-- Safe to run on a fresh DB or one already started by the app once —")
sql("-- all explicit IDs here start at 1000+, well clear of the handful of")
sql("-- rows DataSeeder.java creates (ids 1-5 across a few tables).")
sql("-- ============================================================")
