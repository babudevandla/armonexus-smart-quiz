sql("")

sql("-- ---------------- Question Types ----------------")
question_types = [(7000, "SINGLE_CHOICE"), (7001, "MULTIPLE_CHOICE"), (7002, "TRUE_FALSE"),
                   (7003, "FILL_IN_THE_BLANK"), (7004, "DESCRIPTIVE")]
