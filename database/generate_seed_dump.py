for q_row in quizzes:
    quiz_id_ref = q_row[0]
    bucket = random.choice(["past", "current", "future", "current", "future"])  # weight toward testable states
    if bucket == "past":
        start_offset, end_offset = -14, -7   # closed 7+ days ago
    elif bucket == "current":
        start_offset, end_offset = -2, 5     # open right now
    else:
        start_offset, end_offset = 3, 10     # opens in the future

    sql(f"INSERT INTO quiz_schedules (id, quiz_id, start_time, end_time, active) VALUES "
        f"({sched_id}, {quiz_id_ref}, DATE_ADD(NOW(), INTERVAL {start_offset} DAY), "
        f"DATE_ADD(NOW(), INTERVAL {end_offset} DAY), 1);")
    sched_id += 1
sql("")

sql("-- ---------------- Quiz Assignments (direct-to-user and to-group, mixed) ----------------")
