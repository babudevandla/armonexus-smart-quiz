quizzes = []  # (id, subject_id, duration, total_marks, passing_marks, created_by)
quiz_id = 20000
for i in range(30):
    sid, sname = random.choice(subjects)
    title = random.choice(QUIZ_NAME_TEMPLATES).format(subj=sname, n=(i % 5) + 1)
    duration = random.choice([15, 20, 30, 45, 60])
    created_by = random.choice(instructor_ids)
    active = 1 if random.random() > 0.15 else 0

    subj_questions = [q for q in approved_questions if q[1] == sid]
    chosen = random.sample(subj_questions, k=min(10, len(subj_questions))) if subj_questions else []
    total_marks = sum(q[8] for q in chosen) if chosen else 10
    passing_marks = max(1, int(total_marks * 0.4))

    quizzes.append((quiz_id, sid, duration, total_marks, passing_marks, created_by, chosen))

    sql(f"INSERT INTO quizzes (id, title, description, subject_id, duration_minutes, total_marks, passing_marks, "
        f"shuffle_questions, active, created_by, created_at) VALUES "
        f"({quiz_id}, '{esc(title)}', 'Auto-generated quiz covering {esc(sname)} topics.', {sid}, {duration}, "
        f"{total_marks}, {passing_marks}, 1, {active}, {created_by}, NOW());")
    quiz_id += 1
sql("")

sql("-- ---------------- Quiz Questions (linking table) ----------------")
qq_id = 21000
for q_row in quizzes:
    quiz_id_ref, _sid, _dur, _tm, _pm, _cb, chosen = q_row
    for order, question in enumerate(chosen, start=1):
        sql(f"INSERT INTO quiz_questions (id, quiz_id, question_id, question_order) "
            f"VALUES ({qq_id}, {quiz_id_ref}, {question[0]}, {order});")
        qq_id += 1
sql("")

sql("-- ---------------- Quiz Schedules (mix of past/current/future, to test OPEN/UPCOMING/EXPIRED) ----------------")
