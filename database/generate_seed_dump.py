    q_row = random.choice(quizzes)
    quiz_id_ref, _sid, _dur, total_marks, passing_marks, _cb, _chosen = q_row
    student = random.choice(student_ids)
    score = round(random.uniform(0, total_marks), 1) if total_marks > 0 else 0
    passed = 1 if score >= passing_marks else 0
    days_ago = random.randint(0, 60)
    sql(f"INSERT INTO quiz_results (id, quiz_id, user_id, score_obtained, total_marks, passed, started_at, submitted_at) "
        f"VALUES ({result_id}, {quiz_id_ref}, {student}, {score}, {total_marks}, {passed}, "
        f"DATE_SUB(NOW(), INTERVAL {days_ago} DAY), DATE_SUB(NOW(), INTERVAL {days_ago} DAY));")
    result_id += 1

